# -*- coding: utf-8 -*-
"""
build_translations.py - writes translations/translation_xx.xml from translations_source.py.

    python build_translations.py

Checks that every key has every language and that the printf placeholders match the English text,
so a translation can never crash string.format() in game.
"""
import os
import re
import sys
from xml.sax.saxutils import quoteattr

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from translations_source import LANGUAGES, T  # noqa: E402

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "translations")
PLACEHOLDER = re.compile(r"%[-+ #0]*\d*(?:\.\d+)?[dfsix%]")


def main():
    errors = []
    for key, texts in T.items():
        want = PLACEHOLDER.findall(texts["en"])
        for lang in LANGUAGES:
            text = texts.get(lang)
            if not text:
                errors.append("%s: missing %s" % (key, lang))
                continue
            if PLACEHOLDER.findall(text) != want:
                errors.append("%s [%s]: placeholders %s, English has %s" % (key, lang, PLACEHOLDER.findall(text), want))
    if errors:
        print("\n".join(errors))
        sys.exit(1)

    os.makedirs(OUT_DIR, exist_ok=True)
    for lang in LANGUAGES:
        lines = ['<?xml version="1.0" encoding="utf-8" standalone="no" ?>',
                 '<!-- Generated by tools/build_translations.py - edit tools/translations_source.py instead. -->',
                 '<l10n>', '    <texts>']
        for key in T:
            lines.append('        <text name=%s text=%s/>' % (quoteattr(key), quoteattr(T[key][lang])))
        lines += ['    </texts>', '</l10n>', '']
        path = os.path.join(OUT_DIR, "translation_%s.xml" % lang)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines))
        print("wrote %s (%d texts)" % (os.path.normpath(path), len(T)))


if __name__ == "__main__":
    main()
